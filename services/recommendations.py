def _clean_slug(filename: str) -> str:
    name = filename.rsplit(".", 1)[0]
    if name[:2].isdigit() and name[2:3] == "_":
        name = name[3:]
    return name


def _format_markdown_links(text: str) -> str:
    return re.sub(r"\[([^\]]+)\]\((https?://[^\)]+)\)", r'<a href="\2">\1</a>', text)


def _find_directory(subpath: str) -> Path | None:
    candidates = [
        Path(__file__).resolve().parent.parent / "data" / "recommendations" / subpath,
        Path(__file__).parent.parent / "data" / "recommendations" / subpath,
        Path.cwd() / "data" / "recommendations" / subpath,
        Path.cwd() / "booking" / "data" / "recommendations" / subpath,
        Path.cwd() / "bot_booking" / "data" / "recommendations" / subpath,
    ]
    for c in candidates:
        if c.exists() and any(c.glob("*.md")):
            return c
    return None


def load_items(subpath: str, fallback: dict[str, dict]) -> dict[str, dict]:
    directory = _find_directory(subpath)
    if not directory:
        logger.info("Папка рекомендаций '%s' не найдена на диске. Используем встроенные данные.", subpath)
        return fallback

    items = {}
    try:
        for file_path in sorted(directory.glob("*.md")):
            slug = _clean_slug(file_path.name)
            raw_text = file_path.read_text(encoding="utf-8").strip()

            lines = raw_text.splitlines()
            title = slug
            content_lines = []

            if lines and lines[0].startswith("# "):
                title = lines[0][2:].strip()
                content_lines = lines[1:]
            else:
                content_lines = lines

            content = "\n".join(content_lines).strip()
            links = re.findall(r"\[([^\]]+)\]\((https?://[^\)]+)\)", content)
            html_content = _format_markdown_links(content)

            items[slug] = {
                "slug": slug,
                "title": title,
                "text": html_content,
                "raw": raw_text,
                "links": links,
            }
    except Exception as e:
        logger.warning("Ошибка при чтении файлов из '%s': %s. Используем резервные данные.", directory, e)
        return fallback

    return items if items else fallback


def get_articles() -> dict[str, dict]:
    return load_items("articles", FALLBACK_ARTICLES)


